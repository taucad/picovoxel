// cs2ts: C# PicoGK source -> TypeScript over picovoxel.
//
// The language is translated with Roslyn's semantic model, so every rule keys off a
// resolved symbol or type, never a name pattern:
//   - float32 arithmetic keeps C# semantics: every float-typed operation is wrapped in
//     Math.fround (f), so translated maths produce the same bits as the C#;
//   - user-defined operators become static calls (a - b on Vector3 -> Vector3.op_Subtraction);
//   - members of types outside the translated files keep their C# names and resolve in the
//     runtime module (runtime/picogk.ts), which mirrors PicoGK's C# surface;
//   - an IImplicit's fSignedDistance is also lifted, when its body allows, into a
//     picovoxel SdfExpression (the tape), marked exact when no float32 rounding happens
//     between the coordinate and the final cast (the tape evaluates in double).
// Unsupported constructs do not stop the run: the member becomes a throwing stub and is
// listed in the report, so coverage is measurable.
//
// usage: cs2ts --out <file.ts> --runtime <import path> --translate <a.cs>... --context <dir>...
using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

var opts = ParseArgs(args);
var parse = new CSharpParseOptions(LanguageVersion.Latest);
var translateTrees = opts["--translate"].Select(p => CSharpSyntaxTree.ParseText(File.ReadAllText(p), parse, p)).ToList();
var contextTrees = opts["--context"]
    .SelectMany(d => Directory.EnumerateFiles(d, "*.cs", SearchOption.AllDirectories))
    .Where(p => !opts["--translate"].Any(t => Path.GetFullPath(t) == Path.GetFullPath(p)))
    .Select(p => CSharpSyntaxTree.ParseText(File.ReadAllText(p), parse, p)).ToList();
var refs = ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!).Split(Path.PathSeparator)
    .Select(p => MetadataReference.CreateFromFile(p));
var globalUsings = CSharpSyntaxTree.ParseText(
    "global using System; global using System.Collections.Generic; global using System.IO; global using System.Linq; global using System.Threading; global using System.Threading.Tasks;", parse);
var compilation = CSharpCompilation.Create("cs2ts", translateTrees.Concat(contextTrees).Append(globalUsings), refs,
    new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, allowUnsafe: true, nullableContextOptions: NullableContextOptions.Disable));
var errors = compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error && translateTrees.Contains(d.Location.SourceTree!)).ToList();
foreach (var e in errors.Take(10)) Console.Error.WriteLine($"cs2ts: compile error {e}");

var tr = new Translator(compilation, translateTrees, opts["--runtime"].Single());
string ts = tr.Run();
File.WriteAllText(opts["--out"].Single(), ts);
Console.WriteLine(tr.Report());
return errors.Count == 0 ? 0 : 1;

static Dictionary<string, List<string>> ParseArgs(string[] a)
{
    var d = new Dictionary<string, List<string>> { ["--out"] = new(), ["--runtime"] = new(), ["--translate"] = new(), ["--context"] = new() };
    string? k = null;
    foreach (var s in a) { if (d.ContainsKey(s)) k = s; else if (k != null) d[k].Add(s); }
    return d;
}

sealed class Unsupported(string what) : Exception(what);

sealed class Translator(CSharpCompilation comp, List<SyntaxTree> trees, string runtimePath)
{
    readonly HashSet<INamedTypeSymbol> local = new(SymbolEqualityComparer.Default);
    readonly SortedSet<string> imports = new();
    readonly SortedSet<string> typeImports = new();
    readonly List<string> report = new();
    int membersOk, membersStubbed, lifted, liftedExact;
    SemanticModel model = null!;

    public string Report() =>
        $"cs2ts: {membersOk} members translated, {membersStubbed} stubbed; {lifted} SDFs lifted to tape ({liftedExact} exact)\n" +
        string.Join("\n", report.Select(r => "  " + r));

    public string Run()
    {
        foreach (var t in trees)
            foreach (var c in t.GetRoot().DescendantNodes().OfType<BaseTypeDeclarationSyntax>())
                if (comp.GetSemanticModel(t).GetDeclaredSymbol(c) is INamedTypeSymbol s) local.Add(s);
        var body = new StringBuilder();
        foreach (var t in trees)
        {
            model = comp.GetSemanticModel(t);
            body.Append($"// ---- {Path.GetFileName(t.FilePath)}\n");
            foreach (var c in t.GetRoot().DescendantNodes().OfType<TypeDeclarationSyntax>())
                body.Append(EmitType(c));
        }
        var head = new StringBuilder("// GENERATED by cs2ts from C# source. Do not edit.\n");
        head.Append($"import {{ f, {string.Join(", ", imports)} }} from '{runtimePath}';\n");
        if (typeImports.Count > 0) head.Append($"import type {{ {string.Join(", ", typeImports)} }} from '{runtimePath}';\n");
        head.Append($"import type {{ SdfExpression }} from '../../../src/tape.ts';\n\n");
        return head.Append(body).ToString();
    }

    // ---- types and members ---------------------------------------------------------------
    string EmitType(TypeDeclarationSyntax c)
    {
        var sym = model.GetDeclaredSymbol(c)!;
        var sb = new StringBuilder();
        if (c is InterfaceDeclarationSyntax) return $"export interface {sym.Name} {{}}\n\n";
        var impl = sym.Interfaces.Select(TypeRef).ToList();
        sb.Append($"export class {sym.Name}{(impl.Count > 0 ? " implements " + string.Join(", ", impl) : "")} {{\n");
        foreach (var m in c.Members)
        {
            try
            {
                sb.Append(EmitMember(m, sym));
                membersOk++;
            }
            catch (Exception ex) when (ex is Unsupported or InvalidOperationException or NullReferenceException or InvalidCastException or KeyNotFoundException)
            {
                var u = ex as Unsupported ?? new Unsupported($"translator gap ({ex.GetType().Name})");
                membersStubbed++;
                string name = m switch { MethodDeclarationSyntax md => md.Identifier.Text, ConstructorDeclarationSyntax => "constructor", _ => m.Kind().ToString() };
                report.Add($"stubbed {sym.Name}.{name}: {u.Message}");
                sb.Append(m is MethodDeclarationSyntax md2
                    ? $"  {(md2.Modifiers.Any(SyntaxKind.StaticKeyword) ? "static " : "")}{md2.Identifier.Text}(..._a: unknown[]): never {{ throw new Error('cs2ts: untranslated, {u.Message.Replace("'", "")}'); }}\n"
                    : $"  // cs2ts: untranslated member ({u.Message})\n");
            }
        }
        if (IsImplicit(sym))
        {
            var sdf = c.Members.OfType<MethodDeclarationSyntax>().FirstOrDefault(m => m.Identifier.Text == "fSignedDistance");
            if (sdf != null)
            {
                try
                {
                    var (code, exact) = new Lifter(this, model, sdf).Lift();
                    sb.Append(code).Append($"  get __sdfExact(): boolean {{ return {(exact ? "true" : "false")}; }}\n");
                    lifted++; if (exact) liftedExact++;
                    report.Add($"lifted {sym.Name}.fSignedDistance to tape ({(exact ? "exact" : "fast lane only: float32 rounding inside")})");
                }
                catch (Unsupported u) { report.Add($"not lifted {sym.Name}.fSignedDistance: {u.Message}"); }
            }
        }
        return sb.Append("}\n\n").ToString();
    }

    static bool IsImplicit(INamedTypeSymbol s) => s.AllInterfaces.Any(i => i.Name == "IImplicit" && i.ContainingNamespace.ToDisplayString() == "PicoGK");

    string EmitMember(MemberDeclarationSyntax m, INamedTypeSymbol owner)
    {
        switch (m)
        {
            case FieldDeclarationSyntax fd:
            {
                var sb = new StringBuilder();
                bool st = fd.Modifiers.Any(SyntaxKind.StaticKeyword) || fd.Modifiers.Any(SyntaxKind.ConstKeyword);
                foreach (var v in fd.Declaration.Variables)
                    sb.Append($"  {(st ? "static " : "")}{v.Identifier.Text}: {TsType(fd.Declaration.Type)}{(v.Initializer != null ? " = " + Expr(v.Initializer.Value) : "")};\n");
                return sb.ToString();
            }
            case ConstructorDeclarationSyntax cd:
            {
                if (owner.InstanceConstructors.Count(k => !k.IsImplicitlyDeclared) > 1) throw new Unsupported("constructor overloads");
                if (cd.Initializer != null) throw new Unsupported("constructor chaining");
                return $"  constructor({Params(cd.ParameterList)}) {Block(cd.Body, cd.ExpressionBody, false, "  ")}\n";
            }
            case MethodDeclarationSyntax md:
            {
                var ms = model.GetDeclaredSymbol(md)!;
                if (md.Body == null && md.ExpressionBody == null) return ""; // abstract or partial: JS dispatch needs no declaration
                if (ms.Parameters.Any(p => p.RefKind is RefKind.Out or RefKind.Ref)) throw new Unsupported("ref/out parameter");
                bool st = ms.IsStatic;
                bool isVoid = ms.ReturnsVoid;
                return $"  {(st ? "static " : "")}{MethodName(ms)}({Params(md.ParameterList)}): {(isVoid ? "void" : TsType(ms.ReturnType))} {Block(md.Body, md.ExpressionBody, !isVoid, "  ")}\n";
            }
            case PropertyDeclarationSyntax pd when pd.AccessorList?.Accessors.All(a => a.Body == null && a.ExpressionBody == null) == true:
                return $"  {(pd.Modifiers.Any(SyntaxKind.StaticKeyword) ? "static " : "")}{pd.Identifier.Text}: {TsType(pd.Type)}{(pd.Initializer != null ? " = " + Expr(pd.Initializer.Value) : "")};\n";
            default:
                throw new Unsupported(m.Kind().ToString());
        }
    }

    string MethodName(IMethodSymbol ms)
    {
        var t = ms.ContainingType;
        bool overloaded = local.Contains(t) && t.GetMembers(ms.Name).OfType<IMethodSymbol>().Count() > 1;
        return overloaded ? $"{ms.Name}${ms.Parameters.Length}" : ms.Name;
    }

    string Params(ParameterListSyntax pl) =>
        string.Join(", ", pl.Parameters.Select(p => $"{p.Identifier.Text}: {TsType(p.Type!)}{(p.Default != null ? " = " + Expr(p.Default.Value) : "")}"));

    string Block(BlockSyntax? b, ArrowExpressionClauseSyntax? arrow, bool returns, string ind)
    {
        if (arrow != null) return returns ? $"{{ return {Expr(arrow.Expression)}; }}" : $"{{ {Expr(arrow.Expression)}; }}";
        var sb = new StringBuilder("{\n");
        foreach (var s in b!.Statements) sb.Append(Stmt(s, ind + "  "));
        return sb.Append(ind).Append('}').ToString();
    }

    // ---- statements ------------------------------------------------------------------------
    string Stmt(StatementSyntax s, string ind) => s switch
    {
        BlockSyntax b => ind + "{\n" + string.Concat(b.Statements.Select(x => Stmt(x, ind + "  "))) + ind + "}\n",
        LocalDeclarationStatementSyntax ld => string.Concat(ld.Declaration.Variables.Select(v =>
            $"{ind}let {v.Identifier.Text}{(v.Initializer != null ? " = " + Expr(v.Initializer.Value) : "")};\n")),
        ExpressionStatementSyntax es => $"{ind}{Expr(es.Expression)};\n",
        ReturnStatementSyntax rs => $"{ind}return{(rs.Expression != null ? " " + Expr(rs.Expression) : "")};\n",
        IfStatementSyntax ifs => $"{ind}if ({Expr(ifs.Condition)})\n{Stmt(ifs.Statement, ind + "  ")}" +
                                 (ifs.Else != null ? $"{ind}else\n{Stmt(ifs.Else.Statement, ind + "  ")}" : ""),
        ForStatementSyntax fs when fs.Declaration != null =>
            $"{ind}for (let {string.Join(", ", fs.Declaration.Variables.Select(v => v.Identifier.Text + " = " + Expr(v.Initializer!.Value)))}; " +
            $"{(fs.Condition != null ? Expr(fs.Condition) : "")}; {string.Join(", ", fs.Incrementors.Select(Expr))})\n{Stmt(fs.Statement, ind + "  ")}",
        ForEachStatementSyntax fe => $"{ind}for (const {fe.Identifier.Text} of {Expr(fe.Expression)})\n{Stmt(fe.Statement, ind + "  ")}",
        WhileStatementSyntax ws => $"{ind}while ({Expr(ws.Condition)})\n{Stmt(ws.Statement, ind + "  ")}",
        TryStatementSyntax ts => $"{ind}try\n{Stmt(ts.Block, ind)}" + string.Concat(ts.Catches.Select(c =>
            $"{ind}catch ({c.Declaration?.Identifier.Text ?? "_e"})\n{Stmt(c.Block, ind)}")),
        ThrowStatementSyntax th => $"{ind}throw {(th.Expression != null ? Expr(th.Expression) : "_e")};\n",
        BreakStatementSyntax => $"{ind}break;\n",
        ContinueStatementSyntax => $"{ind}continue;\n",
        EmptyStatementSyntax => "",
        _ => throw new Unsupported(s.Kind().ToString()),
    };

    // ---- expressions -----------------------------------------------------------------------
    static bool IsFloat(ITypeSymbol? t) => t?.SpecialType == SpecialType.System_Single;
    static bool IsInt(ITypeSymbol? t) => t?.SpecialType is SpecialType.System_Int32 or SpecialType.System_Int16 or SpecialType.System_Byte or SpecialType.System_UInt32;
    static bool IsLong(ITypeSymbol? t) => t?.SpecialType is SpecialType.System_Int64 or SpecialType.System_UInt64;

    /// An expression, with the implicit conversion the C# compiler inserts around it.
    public string Expr(ExpressionSyntax e)
    {
        string code = Raw(e);
        var ti = model.GetTypeInfo(e);
        if (IsFloat(ti.ConvertedType) && ti.Type != null && !IsFloat(ti.Type) && e is not LiteralExpressionSyntax)
            code = $"f({code})"; // int/long -> float rounds; double -> float is never implicit
        return code;
    }

    string Raw(ExpressionSyntax e)
    {
        switch (e)
        {
            case LiteralExpressionSyntax lit: return Literal(lit);
            case ParenthesizedExpressionSyntax p: return $"({Expr(p.Expression)})";
            case ThisExpressionSyntax: return "this";
            case IdentifierNameSyntax id: return Name(id, model.GetSymbolInfo(id).Symbol);
            case MemberAccessExpressionSyntax ma: return MemberAccess(ma);
            case InvocationExpressionSyntax inv: return Invocation(inv);
            case ObjectCreationExpressionSyntax oc: return Creation(model.GetTypeInfo(oc).Type!, oc.ArgumentList);
            case ImplicitObjectCreationExpressionSyntax ioc: return Creation(model.GetTypeInfo(ioc).Type!, ioc.ArgumentList);
            case BinaryExpressionSyntax b: return Binary(b);
            case PrefixUnaryExpressionSyntax u when u.IsKind(SyntaxKind.UnaryMinusExpression): return UnaryMinus(u);
            case PrefixUnaryExpressionSyntax u when u.IsKind(SyntaxKind.LogicalNotExpression): return $"!{Expr(u.Operand)}";
            case PrefixUnaryExpressionSyntax u when u.IsKind(SyntaxKind.UnaryPlusExpression): return Expr(u.Operand);
            case PrefixUnaryExpressionSyntax u when u.IsKind(SyntaxKind.PreIncrementExpression) && IsInt(model.GetTypeInfo(u).Type): return $"++{Expr(u.Operand)}";
            case PostfixUnaryExpressionSyntax u when u.IsKind(SyntaxKind.PostIncrementExpression) && IsInt(model.GetTypeInfo(u).Type): return $"{Expr(u.Operand)}++";
            case PostfixUnaryExpressionSyntax u when u.IsKind(SyntaxKind.PostDecrementExpression) && IsInt(model.GetTypeInfo(u).Type): return $"{Expr(u.Operand)}--";
            case CastExpressionSyntax c: return Cast(c);
            case ConditionalExpressionSyntax c: return $"({Expr(c.Condition)} ? {Expr(c.WhenTrue)} : {Expr(c.WhenFalse)})";
            case AssignmentExpressionSyntax a: return Assignment(a);
            case InterpolatedStringExpressionSyntax s:
                return "`" + string.Concat(s.Contents.Select(c => c switch
                {
                    InterpolatedStringTextSyntax t => t.TextToken.Text.Replace("`", "\\`").Replace("\\n", "\\n"),
                    InterpolationSyntax i => "${" + Expr(i.Expression) + "}",
                    _ => throw new Unsupported("interpolation part"),
                })) + "`";
            case ElementAccessExpressionSyntax ea when ea.ArgumentList.Arguments.Count == 1:
                return $"{Expr(ea.Expression)}[{Expr(ea.ArgumentList.Arguments[0].Expression)}]";
            default: throw new Unsupported(e.Kind().ToString());
        }
    }

    static string Num(double d) => d.ToString("R", CultureInfo.InvariantCulture);

    string Literal(LiteralExpressionSyntax lit)
    {
        var v = model.GetConstantValue(lit).Value;
        var target = model.GetTypeInfo(lit).ConvertedType;
        return v switch
        {
            null => "null",
            bool b => b ? "true" : "false",
            string s => System.Text.Json.JsonSerializer.Serialize(s),
            float fl => Num(fl),                                 // a float literal is exactly a double
            int i when IsFloat(target) => Num((float)i),
            double d when IsFloat(target) => Num((float)d),
            IConvertible c => Num(c.ToDouble(CultureInfo.InvariantCulture)),
            _ => throw new Unsupported("literal"),
        };
    }

    public string TypeRef(ITypeSymbol t)
    {
        if (t is INamedTypeSymbol nt && local.Contains(nt)) return nt.Name;
        string ns = t.ContainingNamespace?.ToDisplayString() ?? "";
        if (ns is "PicoGK" or "System.Numerics") { (t.TypeKind == TypeKind.Interface ? typeImports : imports).Add(t.Name); return t.Name; }
        if (ns.StartsWith("System")) throw new Unsupported($"BCL type {t.ToDisplayString()}");
        string obj = ns.Replace('.', '_');
        imports.Add(obj);
        return $"{obj}.{t.Name}";
    }

    string TsType(TypeSyntax ts)
    {
        var t = model.GetTypeInfo(ts).Type;
        if (t == null) return "unknown";
        if (t.SpecialType is SpecialType.System_Single or SpecialType.System_Double or SpecialType.System_Int32 or SpecialType.System_Int64 or SpecialType.System_UInt32 or SpecialType.System_Byte) return "number";
        if (t.SpecialType == SpecialType.System_Boolean) return "boolean";
        if (t.SpecialType == SpecialType.System_String) return "string";
        if (t.SpecialType == SpecialType.System_Void) return "void";
        if (t is IArrayTypeSymbol) return "any[]";
        try { return TypeRef(t); } catch (Unsupported) { return "any"; }
    }
    string TsType(ITypeSymbol t) => t.SpecialType switch
    {
        SpecialType.System_Single or SpecialType.System_Double or SpecialType.System_Int32 or SpecialType.System_Int64 => "number",
        SpecialType.System_Boolean => "boolean",
        SpecialType.System_String => "string",
        _ => t is INamedTypeSymbol n && (local.Contains(n) || n.ContainingNamespace?.ToDisplayString() is "PicoGK" or "System.Numerics") ? TypeRef(t) : "any",
    };

    string Name(SimpleNameSyntax id, ISymbol? s)
    {
        switch (s)
        {
            case ILocalSymbol or IParameterSymbol: return id.Identifier.Text;
            case IFieldSymbol or IPropertySymbol:
                return s.IsStatic ? $"{TypeRef(s.ContainingType)}.{s.Name}" : $"this.{s.Name}";
            case INamedTypeSymbol t: return TypeRef(t);
            case IMethodSymbol m: return m.IsStatic ? $"{TypeRef(m.ContainingType)}.{MethodName(m)}" : $"this.{MethodName(m)}";
            default: throw new Unsupported($"name {id.Identifier.Text}");
        }
    }

    string MemberAccess(MemberAccessExpressionSyntax ma)
    {
        var s = model.GetSymbolInfo(ma).Symbol;
        string? ct = s?.ContainingType?.ToDisplayString();
        if (ct == "System.MathF" && s!.Name == "PI") return Num(MathF.PI);
        if (ct == "System.MathF" && s!.Name == "E") return Num(MathF.E);
        if (ct == "System.Math" && s!.Name is "PI" or "E") return $"Math.{s.Name}";
        if (ct == "System.Exception" && s!.Name == "Message") return $"{Expr(ma.Expression)}.message";
        if (s is { IsStatic: true } && s is not INamedTypeSymbol) return $"{TypeRef(s.ContainingType!)}.{(s is IMethodSymbol m ? MethodName(m) : s.Name)}";
        if (s is INamedTypeSymbol nt) return TypeRef(nt);
        return $"{Expr(ma.Expression)}.{(s is IMethodSymbol m2 ? MethodName(m2) : ma.Name.Identifier.Text)}";
    }

    static readonly HashSet<string> MathFns = new() { "Sin", "Cos", "Tan", "Asin", "Acos", "Atan", "Atan2", "Sqrt", "Abs", "Floor", "Ceiling", "Round", "Exp", "Log", "Pow", "Min", "Max", "Sign", "Cbrt", "Truncate" };
    static string JsMath(string n) => n switch { "Ceiling" => "ceil", "Truncate" => "trunc", _ => char.ToLowerInvariant(n[0]) + n[1..] };

    string Invocation(InvocationExpressionSyntax inv)
    {
        var m = model.GetSymbolInfo(inv).Symbol as IMethodSymbol ?? throw new Unsupported($"unresolved call {inv.Expression}");
        if (m.Parameters.Any(p => p.RefKind is RefKind.Out or RefKind.Ref)) throw new Unsupported($"ref/out call {m.Name}");
        var a = string.Join(", ", inv.ArgumentList.Arguments.Select(x => Expr(x.Expression)));
        string ct = m.ContainingType.ToDisplayString();
        if (ct is "System.Math" or "System.MathF")
        {
            if (!MathFns.Contains(m.Name)) throw new Unsupported($"Math.{m.Name}");
            if (m.Name == "Round") throw new Unsupported("Math.Round (banker's rounding)");
            string call = $"Math.{JsMath(m.Name)}({a})";
            return ct == "System.MathF" || IsFloat(m.ReturnType) ? $"f({call})" : call;
        }
        if (ct == "System.Console" && m.Name == "WriteLine") return $"console.log({a})";
        if (ct.StartsWith("System.") && !ct.StartsWith("System.Numerics")) throw new Unsupported($"BCL call {ct}.{m.Name}");
        if (m.IsExtensionMethod) return $"{TypeRef(m.ContainingType)}.{m.Name}({Expr(((MemberAccessExpressionSyntax)inv.Expression).Expression)}{(a.Length > 0 ? ", " + a : "")})";
        string target = inv.Expression switch
        {
            MemberAccessExpressionSyntax ma when !m.IsStatic => $"{Expr(ma.Expression)}.{MethodName(m)}",
            _ when m.IsStatic => $"{TypeRef(m.ContainingType)}.{MethodName(m)}",
            _ => $"this.{MethodName(m)}",
        };
        return $"{target}({a})";
    }

    string Creation(ITypeSymbol t, ArgumentListSyntax? args) =>
        $"new {TypeRef(t)}({(args == null ? "" : string.Join(", ", args.Arguments.Select(x => Expr(x.Expression))))})";

    static readonly Dictionary<SyntaxKind, string> Ops = new()
    {
        [SyntaxKind.AddExpression] = "+", [SyntaxKind.SubtractExpression] = "-", [SyntaxKind.MultiplyExpression] = "*",
        [SyntaxKind.DivideExpression] = "/", [SyntaxKind.ModuloExpression] = "%",
        [SyntaxKind.LessThanExpression] = "<", [SyntaxKind.LessThanOrEqualExpression] = "<=", [SyntaxKind.GreaterThanExpression] = ">",
        [SyntaxKind.GreaterThanOrEqualExpression] = ">=", [SyntaxKind.EqualsExpression] = "===", [SyntaxKind.NotEqualsExpression] = "!==",
        [SyntaxKind.LogicalAndExpression] = "&&", [SyntaxKind.LogicalOrExpression] = "||",
    };

    string Binary(BinaryExpressionSyntax b)
    {
        var m = model.GetSymbolInfo(b).Symbol as IMethodSymbol;
        if (m != null && m.MethodKind == MethodKind.UserDefinedOperator)
            return $"{TypeRef(m.ContainingType)}.{m.Name}({Expr(b.Left)}, {Expr(b.Right)})";
        if (!Ops.TryGetValue(b.Kind(), out var op)) throw new Unsupported(b.Kind().ToString());
        var t = model.GetTypeInfo(b).Type;
        string l = Expr(b.Left), r = Expr(b.Right);
        if (IsFloat(t) && "+-*/%".Contains(op)) return $"f({l} {op} {r})";
        if (IsInt(t) && op == "*") return $"Math.imul({l}, {r})";
        if (IsInt(t) && "+-/".Contains(op)) return $"(({l} {op} {r}) | 0)";
        if (IsLong(t) && "+-*/".Contains(op)) throw new Unsupported("64-bit integer arithmetic");
        return $"{l} {op} {r}";
    }

    string UnaryMinus(PrefixUnaryExpressionSyntax u)
    {
        var m = model.GetSymbolInfo(u).Symbol as IMethodSymbol;
        if (m != null && m.MethodKind == MethodKind.UserDefinedOperator) return $"{TypeRef(m.ContainingType)}.{m.Name}({Expr(u.Operand)})";
        return $"(-{Expr(u.Operand)})";
    }

    string Cast(CastExpressionSyntax c)
    {
        var t = model.GetTypeInfo(c.Type).Type;
        string inner = Expr(c.Expression);
        if (IsFloat(t)) return $"f({inner})";
        if (IsInt(t)) return $"Math.trunc({inner})";
        return inner;
    }

    string Assignment(AssignmentExpressionSyntax a)
    {
        string l = Expr(a.Left), r = Expr(a.Right);
        if (a.IsKind(SyntaxKind.SimpleAssignmentExpression)) return $"{l} = {r}";
        var t = model.GetTypeInfo(a.Left).Type;
        string op = a.Kind() switch
        {
            SyntaxKind.AddAssignmentExpression => "+", SyntaxKind.SubtractAssignmentExpression => "-",
            SyntaxKind.MultiplyAssignmentExpression => "*", SyntaxKind.DivideAssignmentExpression => "/",
            _ => throw new Unsupported(a.Kind().ToString()),
        };
        var m = model.GetSymbolInfo(a).Symbol as IMethodSymbol;
        if (m != null && m.MethodKind == MethodKind.UserDefinedOperator) return $"{l} = {TypeRef(m.ContainingType)}.{m.Name}({l}, {r})";
        if (IsFloat(t)) return $"{l} = f({l} {op} {r})";
        if (IsInt(t)) return op == "*" ? $"{l} = Math.imul({l}, {r})" : $"{l} = (({l} {op} {r}) | 0)";
        return $"{l} {op}= {r}";
    }
}

/// Lifts fSignedDistance into a runtime-built SdfExpression. Each C# value becomes a
/// Num (TS code yielding a number), a Sym (TS code yielding an SdfExpression that depends
/// on the coordinate) or a Vec of three of those. A symbolic operation whose C# type is
/// float rounds to float32 in C#, which the double-precision tape cannot reproduce, so it
/// clears the exact flag; the final cast to float is the tape's own end truncation.
sealed class Lifter(Translator tr, SemanticModel model, MethodDeclarationSyntax md)
{
    abstract record V;
    sealed record Num(string Code) : V;
    sealed record Sym(string Code) : V;
    sealed record Vec(V X, V Y, V Z) : V;

    readonly Dictionary<string, V> env = new();
    bool exact = true;
    readonly StringBuilder lines = new();
    int tmp;

    public (string, bool) Lift()
    {
        if (md.ParameterList.Parameters.Count != 1) throw new Unsupported("signature");
        var p = md.ParameterList.Parameters[0].Identifier.Text;
        env[p] = new Vec(new Sym("'x'"), new Sym("'y'"), new Sym("'z'"));
        V result;
        if (md.ExpressionBody != null) result = Eval(md.ExpressionBody.Expression, top: true);
        else
        {
            var stmts = md.Body!.Statements;
            for (int i = 0; i < stmts.Count - 1; i++)
            {
                if (stmts[i] is not LocalDeclarationStatementSyntax ld) throw new Unsupported(stmts[i].Kind().ToString());
                foreach (var v in ld.Declaration.Variables) env[v.Identifier.Text] = Bind(v.Identifier.Text, Eval(v.Initializer!.Value));
            }
            if (stmts[^1] is not ReturnStatementSyntax rs) throw new Unsupported("no final return");
            result = Eval(rs.Expression!, top: true);
        }
        var r = result as Sym ?? throw new Unsupported("result does not depend on the coordinate");
        return ($"  __sdf(): SdfExpression {{\n{lines}    return {r.Code};\n  }}\n", exact);
    }

    V Bind(string name, V v)
    {
        switch (v)
        {
            case Num n: lines.Append($"    const {name} = {n.Code};\n"); return new Num(name);
            case Sym s: lines.Append($"    const {name}: SdfExpression = {s.Code};\n"); return new Sym(name);
            case Vec vec: return new Vec(Bind($"{name}_x", vec.X), Bind($"{name}_y", vec.Y), Bind($"{name}_z", vec.Z));
        }
        throw new Unsupported("bind");
    }

    bool DependsOnCoordinate(ExpressionSyntax e) =>
        e.DescendantNodesAndSelf().OfType<IdentifierNameSyntax>().Any(id => env.TryGetValue(id.Identifier.Text, out var v) && !(v is Num) && model.GetSymbolInfo(id).Symbol is ILocalSymbol or IParameterSymbol);

    static bool IsFloat(ITypeSymbol? t) => t?.SpecialType == SpecialType.System_Single;

    V Eval(ExpressionSyntax e, bool top = false)
    {
        if (!DependsOnCoordinate(e))
        {
            var t = model.GetTypeInfo(e).Type;
            if (t?.Name == "Vector3")
                return new Vec(new Num($"({tr.Expr(e)}).X"), new Num($"({tr.Expr(e)}).Y"), new Num($"({tr.Expr(e)}).Z"));
            return new Num(tr.Expr(e));
        }
        var ti = model.GetTypeInfo(e);
        switch (e)
        {
            case ParenthesizedExpressionSyntax p: return Eval(p.Expression, top);
            case IdentifierNameSyntax id: return env[id.Identifier.Text];
            case CastExpressionSyntax c:
            {
                var inner = Eval(c.Expression, top);
                var target = model.GetTypeInfo(c.Type).Type;
                var from = model.GetTypeInfo(c.Expression).Type;
                if (IsFloat(target) && !IsFloat(from) && !top) exact = false; // a float32 rounding mid-expression
                return inner;
            }
            case MemberAccessExpressionSyntax ma when model.GetSymbolInfo(ma).Symbol is IFieldSymbol { Name: "X" or "Y" or "Z" } fld:
            {
                var v = Eval(ma.Expression) as Vec ?? throw new Unsupported("component of a non-vector");
                return fld.Name switch { "X" => v.X, "Y" => v.Y, _ => v.Z };
            }
            case BinaryExpressionSyntax b:
            {
                var m = model.GetSymbolInfo(b).Symbol as IMethodSymbol;
                string op = b.Kind() switch
                {
                    SyntaxKind.AddExpression => "+", SyntaxKind.SubtractExpression => "-",
                    SyntaxKind.MultiplyExpression => "*", SyntaxKind.DivideExpression => "/",
                    _ => throw new Unsupported(b.Kind().ToString()),
                };
                V l = Eval(b.Left), r = Eval(b.Right);
                if (m != null && m.MethodKind == MethodKind.UserDefinedOperator)
                {
                    exact = false; // Vector3 operators round each component to float32
                    if (l is Vec lv && r is Vec rv) return new Vec(Op(op, lv.X, rv.X), Op(op, lv.Y, rv.Y), Op(op, lv.Z, rv.Z));
                    if (l is Vec lv2) return new Vec(Op(op, lv2.X, r), Op(op, lv2.Y, r), Op(op, lv2.Z, r));
                    if (r is Vec rv2) return new Vec(Op(op, l, rv2.X), Op(op, l, rv2.Y), Op(op, l, rv2.Z));
                }
                if (IsFloat(ti.Type)) exact = false;
                return Op(op, l, r);
            }
            case PrefixUnaryExpressionSyntax u when u.IsKind(SyntaxKind.UnaryMinusExpression):
            {
                var v = Eval(u.Operand);
                if (v is Vec vv) { exact = false; return new Vec(Neg(vv.X), Neg(vv.Y), Neg(vv.Z)); }
                if (IsFloat(ti.Type)) exact = false;
                return Neg(v);
            }
            case InvocationExpressionSyntax inv when model.GetSymbolInfo(inv).Symbol is IMethodSymbol m:
            {
                string ct = m.ContainingType.ToDisplayString();
                var args = inv.ArgumentList.Arguments.Select(a => Eval(a.Expression)).ToList();
                if (ct is "System.Math" or "System.MathF")
                {
                    if (ct == "System.MathF" || IsFloat(m.ReturnType)) exact = false;
                    string fn = m.Name switch
                    {
                        "Sin" => "sin", "Cos" => "cos", "Abs" => "abs", "Sqrt" => "sqrt", "Floor" => "floor",
                        "Exp" => "exp", "Log" => "log", "Pow" => "pow", "Min" => "min", "Max" => "max",
                        _ => throw new Unsupported($"Math.{m.Name} has no tape op"),
                    };
                    return new Sym($"['{fn}', {string.Join(", ", args.Select(Code))}]");
                }
                if (m.ContainingType.Name == "Vector3" && m.Name is "Length" or "LengthSquared" && inv.Expression is MemberAccessExpressionSyntax ma)
                {
                    exact = false;
                    var v = Eval(ma.Expression) as Vec ?? throw new Unsupported("Length of a non-vector");
                    var sq = $"['+', ['*', {Code(v.X)}, {Code(v.X)}], ['*', {Code(v.Y)}, {Code(v.Y)}], ['*', {Code(v.Z)}, {Code(v.Z)}]]";
                    return new Sym(m.Name == "Length" ? $"['sqrt', {sq}]" : sq);
                }
                throw new Unsupported($"call {ct}.{m.Name}");
            }
            default: throw new Unsupported(e.Kind().ToString());
        }
    }

    static string Code(V v) => v switch { Num n => n.Code, Sym s => s.Code, _ => throw new Unsupported("vector where a scalar was expected") };
    static V Op(string op, V a, V b) => a is Num na && b is Num nb ? new Num($"f({na.Code} {op} {nb.Code})") : new Sym($"['{op}', {Code(a)}, {Code(b)}]");
    static V Neg(V a) => a is Num n ? new Num($"(-{n.Code})") : new Sym($"['-', {Code(a)}]");
}
