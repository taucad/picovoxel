// Generates src/<variant>.exports.ts: the export names of a built wasm artifact.
//
// Emscripten minifies export names ("F", "Qc", …) and its glue reads them by those
// names, so the only source of truth for "what this glue needs from its module" is
// the module the build produced. `createPicoRuntime({ wasmModule })` checks a
// caller-compiled module against this list before instantiating: a module from
// another build or variant fails with PICO_WASM_INIT_FAILED instead of reaching the
// multi glue, where a missing export surfaces as an unhandled rejection after
// instantiation and the runtime promise never settles.
//
// build-pico-module.sh runs this after each link; test/wasm-exports.test.ts fails
// when a committed list no longer matches its artifact.
//
// Usage: node scripts/generate-wasm-exports.mjs <pico|pico-multi> [wasm dir, default src]

import { readFile, writeFile } from 'node:fs/promises';

/** Renders the generated module for one variant from its wasm bytes. Deterministic. */
export function generateWasmExportsSource(variant, bytes) {
  const names = WebAssembly.Module.exports(new WebAssembly.Module(bytes))
    .map(({ name }) => name)
    .sort();
  const lines = [];
  for (let i = 0; i < names.length; i += 12) {
    lines.push(`  ${names.slice(i, i + 12).map((name) => `'${name}'`).join(', ')},`);
  }
  return `// GENERATED by scripts/generate-wasm-exports.mjs from ${variant}.wasm — do not edit.
// The export names the ${variant}.mjs glue reads from its module (minified by Emscripten).

export const WASM_EXPORTS: readonly string[] = [
${lines.join('\n')}
];
`;
}

const isMain = process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href;
if (isMain) {
  const [variant, dir = new URL('../src/', import.meta.url).pathname] = process.argv.slice(2);
  if (variant !== 'pico' && variant !== 'pico-multi') {
    process.stderr.write('usage: node scripts/generate-wasm-exports.mjs <pico|pico-multi> [wasm dir]\n');
    process.exit(2);
  }
  const bytes = await readFile(`${dir.replace(/\/?$/, '/')}${variant}.wasm`);
  const target = new URL(`../src/${variant}.exports.ts`, import.meta.url);
  await writeFile(target, generateWasmExportsSource(variant, bytes));
  process.stderr.write(`generate-wasm-exports: wrote src/${variant}.exports.ts\n`);
}
